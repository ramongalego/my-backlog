function width({ viewBox, height }: Mark) {
  const [, , w, h] = viewBox.split(' ').map(Number);
  return Math.round(((height * w) / h) * 10) / 10;
}

/**
 * The console a game added by hand is on, as a small chip on its art: the
 * console's logo where there is one, else its name. Purely visual (the name
 * is in the game's meta row for screen readers); hovering shows the name.
 */
export function ConsoleBadge({ platform }: { platform: string }) {
  const known = CONSOLES[platform];
  return (
    <span
      aria-hidden="true"
      title={platform}
      className="inline-flex h-5 max-w-full items-center gap-1 rounded-md bg-ink-950/90 px-1.5 text-xs font-medium text-ink-100"
    >
      {known ? (
        <>
          <svg
            viewBox={known.mark.viewBox}
            width={width(known.mark)}
            height={known.mark.height}
            fill="currentColor"
            className="shrink-0"
          >
            <path d={known.mark.d} />
          </svg>
          {known.suffix && <span className="truncate">{known.suffix}</span>}
        </>
      ) : (
        <span className="truncate">{platform}</span>
      )}
    </span>
  );
}
